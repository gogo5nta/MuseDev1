def current_daypart() -> str:
    h = datetime.now().hour
    if 5 <= h < 11:
        return "morning"
    if 11 <= h < 17:
        return "afternoon"
    if 17 <= h < 22:
        return "evening"
    return "night"


def theme_release(theme, today: date):
    """Returns (released, release_date or None, is_new_today)."""
    offset = theme[4]
    if offset is None:
        return True, None, False
    release = THEME_RELEASE_START + timedelta(days=offset)
    return today >= release, release, today == release


def theme_unlocked(theme, friendship: int, today: date) -> bool:
    released, _, _ = theme_release(theme, today)
    return friendship >= theme[3] and released


def outfit_release(outfit, today: date):
    offset = outfit[3]
    if offset is None:
        return True, None, False
    release = OUTFIT_RELEASE_START + timedelta(days=offset)
    return today >= release, release, today == release


