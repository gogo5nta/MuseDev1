def day_seed(text: str) -> int:
    """Same hash as the original daySeed()."""
    h = 0
    for ch in text:
        h = (h * 31 + ord(ch)) & 0xFFFFFFFF
    return h


def shuffle_seeded(arr, seed_text):
    """Same seeded shuffle as the original shuffleSeeded()."""
    out = list(arr)
    s = day_seed(seed_text)
    for i in range(len(out) - 1, 0, -1):
        s = (s * 1103515245 + 12345) & 0xFFFFFFFF
        j = s % (i + 1)
        out[i], out[j] = out[j], out[i]
    return out


def missions_for_day(day_key: str):
    """Deterministic 3 missions per day, same algorithm as the original."""
    pool = list(MISSIONS)
    chosen = []
    s = day_seed(day_key)
    while len(chosen) < 3 and pool:
        s = (s * 1103515245 + 12345) & 0xFFFFFFFF
        chosen.append(pool.pop(s % len(pool)))
    return chosen


def quiz_for_day(villager, day_key: str):
    idx = day_seed(f"{day_key}:{villager['id']}:quiz") % len(villager["quizzes"])
    question, choices, answer_index, explain = villager["quizzes"][idx]
    shuffled = shuffle_seeded(choices, f"{day_key}:{villager['id']}:quizchoices")
    return question, shuffled, shuffled.index(choices[answer_index]), explain


def shiritori_for_day(villager, day_key: str):
    idx = day_seed(f"{day_key}:{villager['id']}:shiritori") % len(SHIRITORI_ROUNDS)
    start_word, last_kana, choices, answer = SHIRITORI_ROUNDS[idx]
    shuffled = shuffle_seeded(choices, f"{day_key}:{villager['id']}:shiritorichoices")
    return start_word, last_kana, shuffled, answer


